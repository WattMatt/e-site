/**
 * Regenerates apps/web/src/mcp/tools/db/masked-columns.ts from the migrations and the allowlist.
 *
 *   pnpm --filter web exec tsx scripts/mcp/generate-masked-columns.ts
 *
 * Run it whenever masked-columns.contract.test.ts fails because a migration added a column named like money.
 * Then either keep the new column masked (the default) or add it to src/lib/mcp-mask/allowlist.ts with a reason.
 */
import { writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { readMigrations } from '../../src/lib/mcp-mask/mask-candidates'
import { buildMasked } from '../../src/lib/mcp-mask/build-masked'

const webDir = resolve(__dirname, '../..')
const { candidates, tables } = readMigrations(resolve(webDir, '../edge-functions/supabase/migrations'))
const { masked, names } = buildMasked(candidates, tables)

const out = `// GENERATED by scripts/mcp/generate-masked-columns.ts — do not edit; rerun the script.
// Command: pnpm --filter web exec tsx scripts/mcp/generate-masked-columns.ts
export const MASKED: Record<string, { columns: string[]; projectKey: 'project_id' | 'id' | null }> = ${JSON.stringify(masked, null, 2)}

export const MASKED_COLUMN_NAMES: string[] = ${JSON.stringify(names, null, 2)}
`
const target = join(webDir, 'src/mcp/tools/db/masked-columns.ts')
writeFileSync(target, out)
console.log(`${Object.keys(masked).length} tables, ${names.length} distinct column names, ${Object.values(masked).reduce((n, t) => n + t.columns.length, 0)} masked columns -> ${target}`)
